//! The description of a capture: where its data came from.
//!
//! The description is built by the acquisition from the device descriptor. Its fields are
//! private and it has no setters, so a consumer can neither create one nor change it: in
//! particular the `simulated` mark of the virtual device cannot be cleared, and real devices
//! can never carry it.

use std::time::SystemTime;

use crate::capabilities::DeviceId;
use crate::config::Trigger;

/// Where a capture's data came from.
///
/// It cannot be constructed or changed outside this crate:
///
/// ```compile_fail
/// // The fields are private: a consumer cannot build a description ...
/// let _ = la_devices::CaptureDescription {
///     simulated: false,
///     ..unimplemented!()
/// };
/// ```
///
/// ```compile_fail
/// // ... nor clear the simulated mark of an existing one.
/// fn clear(mut d: la_devices::CaptureDescription) {
///     d.simulated = false;
/// }
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CaptureDescription {
    device_id: DeviceId,
    device_name: String,
    simulated: bool,
    seed: Option<u64>,
    requested_sample_rate_hz: u64,
    sample_rate_hz: u64,
    channels: u8,
    enabled_mask: u32,
    trigger: Option<Trigger>,
    samples_before_trigger: u64,
    started_at: SystemTime,
}

/// The values the acquisition knows when it builds a description.
pub(crate) struct DescriptionParts {
    pub(crate) device_id: DeviceId,
    pub(crate) device_name: String,
    pub(crate) simulated: bool,
    pub(crate) seed: Option<u64>,
    pub(crate) sample_rate_hz: u64,
    pub(crate) channels: u8,
    pub(crate) enabled_mask: u32,
    pub(crate) trigger: Option<Trigger>,
}

impl CaptureDescription {
    pub(crate) fn new(parts: DescriptionParts) -> Self {
        Self {
            device_id: parts.device_id,
            device_name: parts.device_name,
            simulated: parts.simulated,
            seed: parts.seed,
            requested_sample_rate_hz: parts.sample_rate_hz,
            sample_rate_hz: parts.sample_rate_hz,
            channels: parts.channels,
            enabled_mask: parts.enabled_mask,
            trigger: parts.trigger,
            samples_before_trigger: 0,
            started_at: SystemTime::now(),
        }
    }

    /// Records what the device reported when it started (the rate in effect and the samples
    /// skipped waiting for the trigger).
    pub(crate) fn apply(&mut self, sample_rate_hz: u64, samples_before_trigger: u64) {
        self.sample_rate_hz = sample_rate_hz;
        self.samples_before_trigger = samples_before_trigger;
    }

    /// The device that produced the data.
    #[must_use]
    pub fn device_id(&self) -> &DeviceId {
        &self.device_id
    }

    /// The name of the device that produced the data.
    #[must_use]
    pub fn device_name(&self) -> &str {
        &self.device_name
    }

    /// `true` if the data was generated by a simulated device and is not a real measurement.
    #[must_use]
    pub fn simulated(&self) -> bool {
        self.simulated
    }

    /// The seed of the virtual device; `None` for real devices.
    #[must_use]
    pub fn seed(&self) -> Option<u64> {
        self.seed
    }

    /// The sample rate the user asked for, in hertz.
    #[must_use]
    pub fn requested_sample_rate_hz(&self) -> u64 {
        self.requested_sample_rate_hz
    }

    /// The sample rate in effect, in hertz.
    #[must_use]
    pub fn sample_rate_hz(&self) -> u64 {
        self.sample_rate_hz
    }

    /// Number of channels in the capture.
    #[must_use]
    pub fn channels(&self) -> u8 {
        self.channels
    }

    /// Which channels carry real data (bit `i` = channel `i`); the others read as zero.
    #[must_use]
    pub fn enabled_mask(&self) -> u32 {
        self.enabled_mask
    }

    /// The configured trigger, if any.
    #[must_use]
    pub fn trigger(&self) -> Option<Trigger> {
        self.trigger
    }

    /// Samples the device skipped while waiting for the trigger (zero without a trigger).
    #[must_use]
    pub fn samples_before_trigger(&self) -> u64 {
        self.samples_before_trigger
    }

    /// Wall-clock time at which the acquisition was created.
    #[must_use]
    pub fn started_at(&self) -> SystemTime {
        self.started_at
    }
}
