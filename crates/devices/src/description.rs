//! The description of a capture: where its data came from.
//!
//! The description is built by the acquisition from the device descriptor. Its fields are
//! private and it has no setters, so a consumer can neither create one nor change it: in
//! particular the `simulated` mark of the virtual device cannot be cleared, and real devices
//! can never carry it.

use std::time::SystemTime;

use la_core::Result;

use crate::capabilities::DeviceId;
use crate::channel_set::ChannelSet;
use crate::config::Trigger;
use crate::error;

/// The longest text (device id or device name) a description may hold, in bytes.
pub const MAX_TEXT_BYTES: usize = 4_096;

/// Where a capture's data came from.
///
/// It cannot be constructed or changed outside this crate:
///
/// ```compile_fail
/// // The fields are private: a consumer cannot build a description ...
/// let _ = la_devices::CaptureDescription {
///     simulated: false,
///     ..unimplemented!()
/// };
/// ```
///
/// ```compile_fail
/// // ... nor clear the simulated mark of an existing one.
/// fn clear(mut d: la_devices::CaptureDescription) {
///     d.simulated = false;
/// }
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CaptureDescription {
    device_id: DeviceId,
    device_name: String,
    simulated: bool,
    seed: Option<u64>,
    requested_sample_rate_hz: u64,
    sample_rate_hz: u64,
    channels: u8,
    enabled_mask: ChannelSet,
    trigger: Option<Trigger>,
    samples_before_trigger: u64,
    started_at: SystemTime,
}

/// The values the acquisition knows when it builds a description.
pub(crate) struct DescriptionParts {
    pub(crate) device_id: DeviceId,
    pub(crate) device_name: String,
    pub(crate) simulated: bool,
    pub(crate) seed: Option<u64>,
    pub(crate) sample_rate_hz: u64,
    pub(crate) channels: u8,
    pub(crate) enabled_mask: ChannelSet,
    pub(crate) trigger: Option<Trigger>,
}

/// Every field of a [`CaptureDescription`] as plain values: the form in which a description is
/// saved in a session file and handed back to [`CaptureDescription::restore`].
///
/// Holding one proves nothing: only [`CaptureDescription::restore`] turns it into a description,
/// and it validates every field.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SavedDescription {
    /// The device id text, `provider:unique`.
    pub device_id: String,
    /// The device name (not empty).
    pub device_name: String,
    /// `true` for data generated by a simulated device.
    pub simulated: bool,
    /// The seed of the virtual device.
    pub seed: Option<u64>,
    /// The sample rate the user asked for, in hertz (at least 1).
    pub requested_sample_rate_hz: u64,
    /// The sample rate in effect, in hertz (at least 1).
    pub sample_rate_hz: u64,
    /// Number of channels in the capture, `1..=160`.
    pub channels: u8,
    /// Enabled channels, not empty, within `channels`.
    pub enabled_mask: ChannelSet,
    /// The configured trigger, on an enabled channel.
    pub trigger: Option<Trigger>,
    /// Samples skipped while waiting for the trigger.
    pub samples_before_trigger: u64,
    /// Wall-clock time at which the acquisition was created.
    pub started_at: SystemTime,
}

impl CaptureDescription {
    pub(crate) fn new(parts: DescriptionParts) -> Self {
        Self {
            device_id: parts.device_id,
            device_name: parts.device_name,
            simulated: parts.simulated,
            seed: parts.seed,
            requested_sample_rate_hz: parts.sample_rate_hz,
            sample_rate_hz: parts.sample_rate_hz,
            channels: parts.channels,
            enabled_mask: parts.enabled_mask,
            trigger: parts.trigger,
            samples_before_trigger: 0,
            started_at: SystemTime::now(),
        }
    }

    /// Every field as plain values, for saving.
    #[must_use]
    pub fn to_saved(&self) -> SavedDescription {
        SavedDescription {
            device_id: self.device_id.as_str().to_owned(),
            device_name: self.device_name.clone(),
            simulated: self.simulated,
            seed: self.seed,
            requested_sample_rate_hz: self.requested_sample_rate_hz,
            sample_rate_hz: self.sample_rate_hz,
            channels: self.channels,
            enabled_mask: self.enabled_mask,
            trigger: self.trigger,
            samples_before_trigger: self.samples_before_trigger,
            started_at: self.started_at,
        }
    }

    /// Rebuilds a description from a saved one. This is the loading path for session files; there
    /// is still no setter, so a description that exists cannot be altered, and every field is
    /// validated so that only what a real acquisition could have produced is accepted.
    ///
    /// # Errors
    ///
    /// `device.invalid_capabilities` for an invalid channel count, rate, id, name or text length;
    /// `device.invalid_channel` for an enabled mask or trigger channel outside the channels.
    pub fn restore(saved: SavedDescription) -> Result<Self> {
        if saved.channels == 0 || saved.channels > la_storage::MAX_CHANNELS {
            return Err(error::invalid_capabilities(
                "the channel count is outside 1..=32",
            ));
        }
        if saved.requested_sample_rate_hz == 0 || saved.sample_rate_hz == 0 {
            return Err(error::invalid_capabilities(
                "a sample rate of zero is not valid",
            ));
        }
        if saved.device_id.len() > MAX_TEXT_BYTES || saved.device_name.len() > MAX_TEXT_BYTES {
            return Err(error::invalid_capabilities(
                "the device id or name is too long",
            ));
        }
        if saved.device_name.trim().is_empty() {
            return Err(error::invalid_capabilities("the device name is empty"));
        }
        let Some(device_id) = DeviceId::from_text(&saved.device_id) else {
            return Err(error::invalid_capabilities(
                "the device id must look like `provider:unique`",
            ));
        };
        if saved.enabled_mask.is_empty()
            || saved
                .enabled_mask
                .highest()
                .is_some_and(|h| h >= saved.channels)
        {
            return Err(error::invalid_channel(
                "the enabled channels are empty or outside the channel count".to_owned(),
            ));
        }
        if let Some(trigger) = saved.trigger {
            if !saved.enabled_mask.contains(trigger.channel) {
                return Err(error::invalid_channel(
                    "the trigger is on a channel that is not enabled".to_owned(),
                ));
            }
        }
        Ok(Self {
            device_id,
            device_name: saved.device_name,
            simulated: saved.simulated,
            seed: saved.seed,
            requested_sample_rate_hz: saved.requested_sample_rate_hz,
            sample_rate_hz: saved.sample_rate_hz,
            channels: saved.channels,
            enabled_mask: saved.enabled_mask,
            trigger: saved.trigger,
            samples_before_trigger: saved.samples_before_trigger,
            started_at: saved.started_at,
        })
    }

    /// Records what the device reported when it started (the rate in effect and the samples
    /// skipped waiting for the trigger).
    pub(crate) fn apply(&mut self, sample_rate_hz: u64, samples_before_trigger: u64) {
        self.sample_rate_hz = sample_rate_hz;
        self.samples_before_trigger = samples_before_trigger;
    }

    /// The device that produced the data.
    #[must_use]
    pub fn device_id(&self) -> &DeviceId {
        &self.device_id
    }

    /// The name of the device that produced the data.
    #[must_use]
    pub fn device_name(&self) -> &str {
        &self.device_name
    }

    /// `true` if the data was generated by a simulated device and is not a real measurement.
    #[must_use]
    pub fn simulated(&self) -> bool {
        self.simulated
    }

    /// The seed of the virtual device; `None` for real devices.
    #[must_use]
    pub fn seed(&self) -> Option<u64> {
        self.seed
    }

    /// The sample rate the user asked for, in hertz.
    #[must_use]
    pub fn requested_sample_rate_hz(&self) -> u64 {
        self.requested_sample_rate_hz
    }

    /// The sample rate in effect, in hertz.
    #[must_use]
    pub fn sample_rate_hz(&self) -> u64 {
        self.sample_rate_hz
    }

    /// Number of channels in the capture.
    #[must_use]
    pub fn channels(&self) -> u8 {
        self.channels
    }

    /// Which channels carry real data; the others read as zero.
    #[must_use]
    pub fn enabled_mask(&self) -> ChannelSet {
        self.enabled_mask
    }

    /// The configured trigger, if any.
    #[must_use]
    pub fn trigger(&self) -> Option<Trigger> {
        self.trigger
    }

    /// Samples the device skipped while waiting for the trigger (zero without a trigger).
    #[must_use]
    pub fn samples_before_trigger(&self) -> u64 {
        self.samples_before_trigger
    }

    /// Wall-clock time at which the acquisition was created.
    #[must_use]
    pub fn started_at(&self) -> SystemTime {
        self.started_at
    }
}
